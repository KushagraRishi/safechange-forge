// Copies the sample hazard log and sample changes into a JS module, so the
// Forge bundle can create them on a judge's site. Run: npm run sync-demo
import { readFileSync, writeFileSync } from 'node:fs';
const root = new URL('..', import.meta.url);
const html = readFileSync(new URL('fixtures/hazard-log.html', root), 'utf8');
const changes = JSON.parse(readFileSync(new URL('fixtures/changes.json', root), 'utf8'));
const pick = ['PUMP-120', 'PUMP-104', 'PUMP-107', 'PUMP-110', 'PUMP-106', 'PUMP-121', 'PUMP-103', 'PUMP-111'];
const demo = pick.map((k) => changes.find((c) => c.key === k)).map(({ key, expect, ...c }) => c);
const out = `// Generated by scripts/sync-demo.js from fixtures/. Do not edit by hand.\nexport const HAZARD_LOG_HTML = ${JSON.stringify(html)};\nexport const DEMO_CHANGES = ${JSON.stringify(demo, null, 2)};\n`;
writeFileSync(new URL('src/demo/content.js', root), out);
console.log(`Wrote ${demo.length} demo changes and the hazard log.`);
