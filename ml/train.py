"""Train the SafeChange hazard model exactly as PREREGISTRATION.md says.

TF-IDF (word 1 and 2 grams, sublinear tf, min_df 2) + one logistic regression
per category (class_weight balanced). C by 5-fold CV on train (micro F2 at 0.5).
Thresholds per category tuned on dev (max F2, grid 0.05 to 0.95).
Exports the frozen model to src/core/model.json for the Forge app, and writes
logs/ml_train.json.
"""
import json, subprocess
import numpy as np
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.linear_model import LogisticRegression
from sklearn.model_selection import KFold
from common import ROOT, CATS, events, splits, gold, to_matrix, micro, fbeta

C_GRID = [0.25, 0.5, 1, 2, 4, 8]
T_GRID = [round(0.05 * i, 2) for i in range(1, 20)]


def vectorizer():
    return TfidfVectorizer(lowercase=True, ngram_range=(1, 2), sublinear_tf=True, min_df=2,
                           token_pattern=r"(?u)\b\w\w+\b", norm="l2", smooth_idf=True)


def fit(texts, Y, C):
    vec = vectorizer()
    X = vec.fit_transform(texts)
    models = []
    for j in range(len(CATS)):
        y = Y[:, j]
        if y.sum() == 0 or y.sum() == len(y):
            models.append(None)  # nothing to learn: constant
            continue
        m = LogisticRegression(C=C, class_weight="balanced", solver="liblinear", max_iter=2000)
        m.fit(X, y)
        models.append(m)
    return vec, models


def proba(vec, models, texts):
    X = vec.transform(texts)
    out = np.zeros((len(texts), len(CATS)))
    for j, m in enumerate(models):
        out[:, j] = m.predict_proba(X)[:, 1] if m is not None else 0.0
    return out


def main():
    ev, sp = events(), splits()
    tr_ids, dv_ids = sp["train"], sp["dev"]
    tr_lab, dv_lab = gold("train"), gold("dev")
    tr_txt = [ev[i]["text"] for i in tr_ids]
    Ytr = np.array(to_matrix(tr_ids, tr_lab))

    # 1. choose C by 5-fold CV on train
    kf = KFold(n_splits=5, shuffle=True, random_state=0)
    cv = {}
    for C in C_GRID:
        scores = []
        for a, b in kf.split(tr_txt):
            vec, ms = fit([tr_txt[i] for i in a], Ytr[a], C)
            P = (proba(vec, ms, [tr_txt[i] for i in b]) >= 0.5).astype(int)
            scores.append(micro(Ytr[b].tolist(), P.tolist())["f2"])
        cv[str(C)] = float(np.mean(scores))
    best_C = max(C_GRID, key=lambda c: (cv[str(c)], -c))

    # 2. fit on all train
    vec, models = fit(tr_txt, Ytr, best_C)

    # 3. thresholds on dev
    dv_txt = [ev[i]["text"] for i in dv_ids]
    Ydv = np.array(to_matrix(dv_ids, dv_lab))
    Pdv = proba(vec, models, dv_txt)
    thresholds = {}
    for j, c in enumerate(CATS):
        if Ydv[:, j].sum() == 0:
            thresholds[c] = 0.5
            continue
        best = max(T_GRID, key=lambda t: (fbeta(int(((Pdv[:, j] >= t) & (Ydv[:, j] == 1)).sum()),
                                                  int(((Pdv[:, j] >= t) & (Ydv[:, j] == 0)).sum()),
                                                  int(((Pdv[:, j] < t) & (Ydv[:, j] == 1)).sum())), t))
        thresholds[c] = best
    dev_pred = np.column_stack([(Pdv[:, j] >= thresholds[c]).astype(int) for j, c in enumerate(CATS)])
    dev_metrics = micro(Ydv.tolist(), dev_pred.tolist())

    # 4. export for the Forge app (JS reimplements transform + sigmoid)
    vocab = vec.vocabulary_
    terms = sorted(vocab, key=lambda t: vocab[t])
    idf = vec.idf_
    coef = {c: ([round(float(x), 6) for x in models[j].coef_[0]] if models[j] is not None else None)
            for j, c in enumerate(CATS)}
    intercept = {c: (round(float(models[j].intercept_[0]), 6) if models[j] is not None else None)
                 for j, c in enumerate(CATS)}
    commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True, text=True).stdout.strip()
    model = {
        "about": "SafeChange hazard model. TF-IDF (1-2 grams) + logistic regression per category, trained on FDA software recall events (openFDA). See ml/PREREGISTRATION.md.",
        "categories": CATS, "terms": terms, "idf": [round(float(x), 6) for x in idf],
        "coef": coef, "intercept": intercept, "thresholds": thresholds, "C": best_C,
        "train_events": len(tr_ids), "trained_at_commit": commit,
    }
    blob = json.dumps(model, separators=(",", ":"))
    (ROOT / "src" / "core" / "model.json").write_text(blob)
    (ROOT / "src" / "core" / "model-data.js").write_text(
        "// Generated by ml/train.py. Do not edit. Same content as model.json.\nexport default " + blob + ";\n")
    # Reference probabilities for the Python to JS parity test (dev texts only).
    ref = [{"text": t, "p": [round(float(x), 6) for x in row]} for t, row in zip(dv_txt[:60], Pdv[:60])]
    (ROOT / "test" / "fixtures").mkdir(exist_ok=True)
    (ROOT / "test" / "fixtures" / "model_parity.json").write_text(json.dumps(ref))
    log = {"cv_micro_f2_by_C": cv, "best_C": best_C, "thresholds": thresholds, "vocab_size": len(terms),
           "train_label_counts": {c: int(Ytr[:, j].sum()) for j, c in enumerate(CATS)},
           "dev_label_counts": {c: int(Ydv[:, j].sum()) for j, c in enumerate(CATS)},
           "dev_micro": dev_metrics, "commit": commit}
    (ROOT / "logs").mkdir(exist_ok=True)
    (ROOT / "logs" / "ml_train.json").write_text(json.dumps(log, indent=2) + "\n")
    print(json.dumps(log, indent=2))


if __name__ == "__main__":
    main()
